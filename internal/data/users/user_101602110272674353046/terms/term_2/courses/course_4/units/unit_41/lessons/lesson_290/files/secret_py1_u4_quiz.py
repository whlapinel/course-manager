# Part 1: Functions

# 1. Write a function `double(num)` that takes a number and returns twice its value. Call the function with the number 7.

# 2. Write a function `greet(name)` that takes a name as a parameter and prints 'Hello, name!'. Call the function with 'Alice'.

# Part 2: Exceptions

# 1. Write a function `safe_divide(a, b)` that divides `a` by `b` but catches a ZeroDivisionError and returns 'Cannot divide by zero'. Call the function with 10 and 0.

# 2. Write a function `safe_int(s)` that converts a string to an integer but catches a ValueError and returns 'Invalid number'. Call the function with 'abc'.

# Part 3: Modules

# 1. Write a script that imports the `math` module and prints the square root of 25.

# 2. Write a script that imports the `random` module and prints a random number between 1 and 10.
